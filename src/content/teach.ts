// Le lezioni sui comandi, raccontate da Nyx. Ogni volta che il corso sta per chiedere
// un comando nuovo, la lezione lo spiega da capo: a cosa serve, com'è fatto pezzo per
// pezzo, cosa risponde davvero il terminale e come si legge la risposta, gli errori che
// si fanno all'inizio e cosa vogliono dire. Gli esempi vengono eseguiti sul deck nel
// momento in cui la lezione viene mostrata: l'output è quello vero.

export interface Teach {
  /** Nyx: perché ti serve, in parole semplici */
  why: string;
  /** cosa fa, in uno o più paragrafi (se manca si usa la descrizione del Manuale) */
  what?: string[];
  /** la forma del comando che si usa adesso */
  form: string;
  /** i pezzi del comando, uno per uno */
  parts: [string, string][];
  /** comandi da eseguire per mostrare la risposta vera */
  demo: string[];
  /** come si legge la risposta */
  read?: string[];
  /** esempio dal vivo per un'opzione (chiave: l'opzione, es. "-a") */
  optDemo?: Record<string, string>;
  /** errori tipici: comando sbagliato e spiegazione del messaggio */
  mistakes?: [string, string][];
  /** Nyx: la cosa da ricordare */
  remember: string;
}

